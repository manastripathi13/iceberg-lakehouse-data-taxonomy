"""Enforce the data taxonomy against the live Iceberg catalog.

Reads table metadata straight from Nessie's Iceberg REST API (no Spark needed),
checks every table against `governance/taxonomy.yml`, and can write a
human-readable data catalog (docs/DATA_CATALOG.md).

Usage:
    python governance/check_taxonomy.py                # check main, all layers
    python governance/check_taxonomy.py --ref ingest_batch_002 --namespaces bronze
    python governance/check_taxonomy.py --write-catalog
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path
from urllib.parse import quote

import requests
import yaml

ROOT = Path(__file__).resolve().parents[1]
TAXONOMY = yaml.safe_load((ROOT / "governance" / "taxonomy.yml").read_text())
ICEBERG = os.getenv("NESSIE_ICEBERG", "http://localhost:19120/iceberg/v1")


def _prefix(ref: str) -> str:
    return quote(f"{ref}|warehouse", safe="")


def list_tables(ref: str, namespace: str) -> list[str]:
    r = requests.get(f"{ICEBERG}/{_prefix(ref)}/namespaces/{namespace}/tables", timeout=10)
    if r.status_code == 404:
        return []
    r.raise_for_status()
    return [t["name"] for t in r.json().get("identifiers", [])]


def load_table(ref: str, namespace: str, table: str) -> dict:
    r = requests.get(f"{ICEBERG}/{_prefix(ref)}/namespaces/{namespace}/tables/{table}", timeout=10)
    r.raise_for_status()
    meta = r.json()["metadata"]
    schema = next(s for s in meta["schemas"] if s["schema-id"] == meta["current-schema-id"])
    return {
        "properties": meta.get("properties", {}),
        "columns": [(f["name"], f["type"] if isinstance(f["type"], str) else f["type"].get("type")) for f in schema["fields"]],
        "snapshots": len(meta.get("snapshots", [])),
        "schema_versions": len(meta["schemas"]),
        "partition": [f["name"] for s in meta.get("partition-specs", []) if s["spec-id"] == meta.get("default-spec-id") for f in s["fields"]],
    }


def validate_table(layer: str, table: str, props: dict, columns: set[str]) -> list[str]:
    """Check one table against the taxonomy. Pure function, so it is easy to unit test."""
    rules = TAXONOMY["layers"][layer]
    fq = f"{layer}.{table}"
    problems = []
    if not re.match(rules["name_pattern"], table):
        problems.append(f"{fq}: name does not match {layer} pattern")
    for p in TAXONOMY["required_table_properties"]:
        if not props.get(p):
            problems.append(f"{fq}: missing table property '{p}'")
    if props.get("layer") and props["layer"] != layer:
        problems.append(f"{fq}: property layer={props['layer']} but lives in {layer}")
    if props.get("domain") and props["domain"] not in TAXONOMY["domains"] and props["domain"] != "revenue":
        problems.append(f"{fq}: unknown domain '{props['domain']}'")
    if props.get("pii", "none") not in TAXONOMY["pii_levels"]:
        problems.append(f"{fq}: invalid pii level")
    for c in rules.get("required_columns", []):
        if c not in columns:
            problems.append(f"{fq}: missing required column '{c}'")
    return problems


def check_catalog(ref: str = "main", namespaces: list[str] | None = None, collect: dict | None = None) -> list[str]:
    problems: list[str] = []
    for layer in namespaces or list(TAXONOMY["layers"]):
        for table in list_tables(ref, layer):
            t = load_table(ref, layer, table)
            if collect is not None:
                collect[f"{layer}.{table}"] = t
            problems += validate_table(layer, table, t["properties"], {c for c, _ in t["columns"]})
    return problems


def write_catalog(tables: dict, ref: str) -> Path:
    out = ROOT / "docs" / "DATA_CATALOG.md"
    lines = [f"# Data catalog (generated from Nessie ref `{ref}`)", "",
             "Generated by `governance/check_taxonomy.py --write-catalog`. Do not edit by hand.", ""]
    for layer in TAXONOMY["layers"]:
        names = sorted(k for k in tables if k.startswith(layer + "."))
        if not names:
            continue
        lines += [f"## {layer.title()}", "", f"_{TAXONOMY['layers'][layer]['purpose']}_", "",
                  "| Table | Domain | Owner | PII | Snapshots | Schema versions | Description |",
                  "|---|---|---|---|---|---|---|"]
        for n in names:
            p = tables[n]["properties"]
            lines.append(f"| `{n}` | {p.get('domain','')} | {p.get('data_owner','')} | {p.get('pii','')} | "
                         f"{tables[n]['snapshots']} | {tables[n]['schema_versions']} | {p.get('description','')} |")
        lines.append("")
    for layer in TAXONOMY["layers"]:
        for n in sorted(k for k in tables if k.startswith(layer + ".")):
            lines += [f"### `{n}`", "", "| Column | Type |", "|---|---|"]
            lines += [f"| {c} | {t} |" for c, t in tables[n]["columns"]]
            lines.append("")
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines))
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--ref", default="main")
    ap.add_argument("--namespaces", nargs="*")
    ap.add_argument("--write-catalog", action="store_true")
    a = ap.parse_args()
    tables: dict = {}
    problems = check_catalog(a.ref, a.namespaces, collect=tables)
    print(f"checked {len(tables)} tables on '{a.ref}'")
    for p in problems:
        print("  FAIL", p)
    if a.write_catalog:
        print("catalog written to", write_catalog(tables, a.ref).relative_to(ROOT))
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
